"""
gap_analyzer.py: turns quiz scores + the concept graph into recommendations.

Pure functions. No FastAPI, Gemini, or database imports. Every number and every
sentence of explanation comes from real scores and graph data. Nothing is
generated by an LLM.

Typical route usage:
    results = build_results(session_id, concept_scores, concepts)
"""

from graph_engine import build_adjacency, count_descendants, topological_order
from models import (
    Classification,
    Concept,
    ConceptScore,
    LearningRecommendation,
    ResultsResponse,
)

# ---------- Tunable constants ----------

STRONG_THRESHOLD = 0.80      # score >= this  -> strong
DEVELOPING_THRESHOLD = 0.50  # score >= this  -> developing, otherwise weak
DESCENDANT_WEIGHT = 0.25     # how much each downstream concept raises priority

MAX_NAMED_DEPENDENTS = 3     # how many dependent names to list in explanations


# ---------- Scoring ----------

def classify(score: float | None) -> Classification:
    """Map a 0-1 score to strong / developing / weak. None means not assessed."""
    if score is None:
        return "unknown"
    if score >= STRONG_THRESHOLD:
        return "strong"
    if score >= DEVELOPING_THRESHOLD:
        return "developing"
    return "weak"


def make_concept_score(concept_id: str, correct: int, total: int) -> ConceptScore:
    """Build a ConceptScore from raw counts. total == 0 means unassessed (score None, not 0)."""
    if total == 0:
        return ConceptScore(concept_id=concept_id, correct=0, total=0)
    score = correct / total
    return ConceptScore(
        concept_id=concept_id,
        correct=correct,
        total=total,
        score=score,
        classification=classify(score),
    )


def overall_score(concept_scores: list[ConceptScore]) -> float:
    """Total correct answers / total questions across all assessed concepts."""
    total = sum(s.total for s in concept_scores)
    if total == 0:
        return 0.0
    return sum(s.correct for s in concept_scores) / total


def priority(score: float, descendant_count: int) -> float:
    """Review priority = (1 - score) * (1 + 0.25 * descendants). Higher = review sooner."""
    return (1 - score) * (1 + DESCENDANT_WEIGHT * descendant_count)


def _assessed(concept_scores: list[ConceptScore], concepts: list[Concept]) -> dict[str, ConceptScore]:
    """Scores that count: assessed (score not None) AND present in the graph."""
    known = {c.id for c in concepts}
    return {
        s.concept_id: s
        for s in concept_scores
        if s.score is not None and s.concept_id in known
    }


def rank_priorities(
    concept_scores: list[ConceptScore], concepts: list[Concept]
) -> list[tuple[str, float]]:
    """(concept_id, priority) for assessed concepts only, highest priority first.

    Unassessed concepts are skipped entirely: not assessed is not the same as failed.
    This is a pure ranking and is NOT a valid study order. Use build_learning_path for that.
    """
    descendants = count_descendants(concepts)
    assessed = _assessed(concept_scores, concepts)
    ranked = [(cid, priority(s.score, descendants[cid])) for cid, s in assessed.items()]
    ranked.sort(key=lambda pair: -pair[1])
    return ranked


# ---------- Explanations ----------

def _plural(n: int, word: str) -> str:
    return f"{n} {word}" if n == 1 else f"{n} {word}s"


def _join_names(names: list[str]) -> str:
    if len(names) <= 1:
        return "".join(names)
    return ", ".join(names[:-1]) + " and " + names[-1]


def explain(
    concept_name: str,
    score: float,
    classification: Classification,
    descendant_count: int,
    priority_value: float,
    dependent_names: list[str],
) -> str:
    """Template-based explanation using only real numbers. Cautious wording on purpose."""
    pct = round(score * 100)

    if classification == "weak":
        opener = f"Your quiz results suggest a potential gap in {concept_name} ({pct}% correct)."
    elif classification == "developing":
        opener = (
            f"You answered {pct}% of the {concept_name} questions correctly, "
            f"so this concept may need reinforcement."
        )
    else:
        opener = f"You answered {pct}% of the {concept_name} questions correctly."

    if descendant_count == 0:
        impact = "No other concepts in your graph depend on it."
    else:
        impact = f"{_plural(descendant_count, 'other concept')} in your graph build on it"
        shown = dependent_names[:MAX_NAMED_DEPENDENTS]
        if shown:
            impact += f", including {_join_names(shown)}"
        impact += "."

    if classification == "strong":
        action = "No review needed."
    elif dependent_names:
        action = f"Review {concept_name} before moving on to {dependent_names[0]}."
    else:
        action = f"Practice a few more {concept_name} questions to confirm your understanding."

    return f"{opener} {impact} Review priority: {priority_value:.2f}. {action}"


# ---------- Learning path ----------

def build_learning_path(
    concept_scores: list[ConceptScore], concepts: list[Concept]
) -> list[LearningRecommendation]:
    """Ordered study plan for weak and developing concepts.

    - Strong and unassessed concepts are left out.
    - Order is a topological sort of the WHOLE graph (prerequisites first), using
      priority only to choose between concepts that are available at the same time.
      So a high-priority dependent can never jump ahead of its prerequisite.

    Raises ValueError if the graph has a cycle (validate it first).
    """
    assessed = _assessed(concept_scores, concepts)
    descendants = count_descendants(concepts)
    adjacency = build_adjacency(concepts)
    names = {c.id: c.name for c in concepts}

    priorities = {cid: priority(s.score, descendants[cid]) for cid, s in assessed.items()}
    order = topological_order(concepts, priority=priorities)

    path: list[LearningRecommendation] = []
    for cid in order:
        s = assessed.get(cid)
        if s is None or s.classification not in ("weak", "developing"):
            continue
        path.append(
            LearningRecommendation(
                concept_id=cid,
                concept_name=names[cid],
                score=s.score,
                classification=s.classification,
                descendant_count=descendants[cid],
                priority=priorities[cid],
                explanation=explain(
                    concept_name=names[cid],
                    score=s.score,
                    classification=s.classification,
                    descendant_count=descendants[cid],
                    priority_value=priorities[cid],
                    dependent_names=[names[d] for d in adjacency[cid]],
                ),
                position=len(path) + 1,
            )
        )
    return path


def build_results(
    session_id: str, concept_scores: list[ConceptScore], concepts: list[Concept]
) -> ResultsResponse:
    """One call for the route: everything the results screen needs."""
    return ResultsResponse(
        session_id=session_id,
        overall_score=overall_score(concept_scores),
        concept_scores=concept_scores,
        recommendations=build_learning_path(concept_scores, concepts),
    )